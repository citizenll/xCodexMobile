const dictionaries: Record<Locale, typeof zhCN> = {
  "zh-CN": zhCN,
};

let activeLocale: Locale = "zh-CN";

export type TranslationKey = keyof typeof zhCN;

export function setLocale(locale: Locale): void {
  activeLocale = locale;
}

export function getLocale(): Locale {
  return activeLocale;
}

export function t(key: TranslationKey, params?: TranslationParams): string {
  const template = dictionaries[activeLocale][key] ?? key;
  return formatTranslation(template, params);
}

export function translateText(key: string, params?: TranslationParams): string {
  const template = (dictionaries[activeLocale] as Record<string, string>)[key] ?? key;
  return formatTranslation(template, params);
}

function formatTranslation(template: string, params?: TranslationParams): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name];
    return value === null || value === undefined ? match : String(value);
  });
}
